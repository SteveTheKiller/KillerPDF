#Requires -Version 5.1
<#
.SYNOPSIS
    Generates Diagnostics\EmbeddedTelemetry.Generated.cs from an
    Application Insights connection string in the environment.

.DESCRIPTION
    Called from release.ps1 just before `dotnet publish`. Reads the
    connection string from $env:TDPDF_APPINSIGHTS_CONN (NEVER as a
    command-line argument, so it can't leak via process listings) and
    writes a gitignored partial class containing the AES-256-CBC
    ciphertext plus an XOR-split key.

    When the env var is empty or unset, this script does nothing — the
    published EXE falls back to the placeholder constants (all empty)
    and ships with no embedded key. That is the correct behavior for
    dev builds, CI builds, and the GPLv3 source bundle.

    The generated file is gitignored. TDPdf.csproj excludes the
    placeholder EmbeddedTelemetry.cs from compilation when the
    generated file is present, so the real values take effect.

.PARAMETER ProjectDir
    Path to the TDPdf project root (where TDPdf.csproj lives).

.PARAMETER Remove
    Delete the generated file instead of writing it. Used by release.ps1
    after publish to keep the working tree clean.
#>
param(
    [Parameter(Mandatory)][string]$ProjectDir,
    [switch]$Remove
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$generated = Join-Path $ProjectDir 'Diagnostics\EmbeddedTelemetry.Generated.cs'

if ($Remove) {
    if (Test-Path $generated) {
        Remove-Item -Force $generated
        Write-Host "    Removed: $generated" -ForegroundColor DarkGray
    }
    return
}

$conn = $env:TDPDF_APPINSIGHTS_CONN
if ([string]::IsNullOrWhiteSpace($conn)) {
    Write-Host "    No `$env:TDPDF_APPINSIGHTS_CONN — building without embedded telemetry key." -ForegroundColor Yellow
    if (Test-Path $generated) { Remove-Item -Force $generated }
    return
}

# Sanity check: connection string should look like an App Insights one.
if ($conn -notmatch 'InstrumentationKey=') {
    throw "TDPDF_APPINSIGHTS_CONN doesn't look like an App Insights connection string (missing 'InstrumentationKey=')."
}

# Generate fresh AES-256 key + IV per build. Splitting the key with a
# random XOR mask is a "speed bump" — both halves end up in TDPdf.exe.
# Don't oversell this; it just stops the trivial strings/grep attack.
$key  = New-Object byte[] 32
$iv   = New-Object byte[] 16
$mask = New-Object byte[] 32
$rng  = [System.Security.Cryptography.RandomNumberGenerator]::Create()
try {
    $rng.GetBytes($key)
    $rng.GetBytes($iv)
    $rng.GetBytes($mask)
} finally {
    $rng.Dispose()
}

$keyPart1 = New-Object byte[] 32
for ($i = 0; $i -lt 32; $i++) { $keyPart1[$i] = [byte]($key[$i] -bxor $mask[$i]) }
$keyPart2 = $mask

$aes = [System.Security.Cryptography.Aes]::Create()
try {
    $aes.KeySize  = 256
    $aes.Mode     = [System.Security.Cryptography.CipherMode]::CBC
    $aes.Padding  = [System.Security.Cryptography.PaddingMode]::PKCS7
    $aes.Key      = $key
    $aes.IV       = $iv

    $encryptor = $aes.CreateEncryptor()
    try {
        $plain      = [System.Text.Encoding]::UTF8.GetBytes($conn)
        $ciphertext = $encryptor.TransformFinalBlock($plain, 0, $plain.Length)
        [Array]::Clear($plain, 0, $plain.Length)
    } finally {
        $encryptor.Dispose()
    }
} finally {
    $aes.Dispose()
}

$ctB64 = [Convert]::ToBase64String($ciphertext)
$k1B64 = [Convert]::ToBase64String($keyPart1)
$k2B64 = [Convert]::ToBase64String($keyPart2)
$ivB64 = [Convert]::ToBase64String($iv)

# Wipe sensitive byte arrays.
[Array]::Clear($key, 0, $key.Length)
[Array]::Clear($keyPart1, 0, $keyPart1.Length)
[Array]::Clear($keyPart2, 0, $keyPart2.Length)
[Array]::Clear($mask, 0, $mask.Length)

$content = @"
// <auto-generated />
// GENERATED FILE — DO NOT EDIT, DO NOT COMMIT.
// Produced by build\embed-telemetry-key.ps1 from `$env:TDPDF_APPINSIGHTS_CONN
// at release time. Gitignored. Replaces the placeholder constants in
// EmbeddedTelemetry.cs via the conditional <Compile Remove> in TDPdf.csproj.
namespace TDPdf.Diagnostics
{
    internal static partial class EmbeddedTelemetry
    {
        internal const string CiphertextB64 = "$ctB64";
        internal const string KeyPart1B64   = "$k1B64";
        internal const string KeyPart2B64   = "$k2B64";
        internal const string IvB64         = "$ivB64";
    }
}
"@

[System.IO.File]::WriteAllText($generated, $content, [System.Text.UTF8Encoding]::new($false))
Write-Host "    Wrote: $generated" -ForegroundColor Green
